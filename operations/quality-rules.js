 function blocked(clause,match,inheritedPlan,code){
  const before=clause.slice(0,match.index),after=clause.slice(match.index+match[0].length);
  if(!['M','O'].includes(code)&&/^(?:争取|准备|计划|打算|希望|想要|询问|问问|待)/.test(match[0]))return true;
  if(['E','O'].includes(code)&&/(?:不愿意|不愿|不想|不需要|拒绝|不再|不)$/.test(before))return true;
  if(code==='O'&&/(?:不想|不愿|不需要|没有|无).{0,12}(?:买|购|租|出售)/.test(match[0]))return true;
  if(code==='P'&&/\d$/.test(match[0])&&/^(?:天|日|周|月|年|号|次|个|页|份|小时|分钟)/.test(after))return true;
  if(/(?:沟通|讨论|探讨|聊|谈|问|询问|看看)(?:了|过|一下|了下|是否|能否|关于|有关|的|下|能不能|要不要)?$/.test(before))return true;
  // These negate or propose the information-gathering action, not the owner's actual stance.
  const pending=/(?:看看|看一下|询问|问问|问一下|咨询|尝试|争取|打算|准备|计划|尚待|有待|待|希望|下次|明天|下周)[^，,。；;\n]{0,14}$/;
  const unknown=/(?:是否|能否|要不要|有没有)[^，,。；;\n]{0,10}$/;
  const negation=/(?:尚未|还未|没有|还没|未|没)(?:能|有)?(?:获取|取得|拿到|得到|获悉|问到|确认|明确|了解|核实|同意|完成|签署|发现)?[^，,。；;\n]{0,5}$/;
  const done=/(?:已经|已|确认了|明确了|了解到|了解了|获悉|得知|拿到了|取得了)[^，,。；;\n]{0,10}$/;
  const blockers=[pending.exec(before),unknown.exec(before),negation.exec(before)].filter(Boolean),lastBlock=Math.max(-1,...blockers.map(m=>m.index)),lastDone=done.exec(before)?.index??-1;
  if(lastBlock>=0&&lastDone<=lastBlock)return true;
  if(inheritedPlan&&!done.test(before)&&!/(?:业主|房东)(?:说|表示|确认|同意)/.test(before))return true;
  if(/^(?:的)?(?:计划|安排)(?:尚未|未|待|已确定)|^(?:也|仍)?(?:尚未|未|没有|没|待)(?:确认|完成|落实|取得|拿到|同意)/.test(after))return true;
  return false;
 }
 function analyze(text){
  const evidence=[],source=String(text??'');
  for(const sentence of source.split(/[。；;！!？?\n]/)){
   let inheritedPlan=false;
   for(const match of sentence.matchAll(/(?:了解了|了解到|已了解)[^。；;\n]{0,30}[，,、](?:以及|和)?(?:出售心态和价格|价格|底价|报价)/g)){
    if(!blocked(sentence,match,false,'P'))evidence.push({code:'P',level:1,reason:'已获取价格信息，具体金额可补',quote:match[0],text:sentence.trim()});
   }
   for(const clause of sentence.split(/[，,]|但是|但|同时|并且/)){
    if(/看房|带看/.test(source))for(const match of clause.matchAll(/(?:业主|房东)(?:这边|那边)?(?:诚意|愿意|不愿意|不)?配合/g)){
     if(!blocked(clause,match,inheritedPlan,'V'))evidence.push({code:'V',level:2,reason:'已确认看房配合',quote:match[0],text:clause.trim()});
    }
    for(const rule of rules){
     for(const match of clause.matchAll(new RegExp(rule.pattern.source,'g'))){
      if(blocked(clause,match,inheritedPlan,rule.code))continue;
      if(rule.code==='P'&&/(?:礼物|礼品|水果|花了|贷款|抵押|还款|美金|装修费)/.test(clause)&&!/(?:底价|报价|单价|裸房价|出价|交易|价格|可卖|能卖)/.test(clause))continue;
      evidence.push({code:rule.code,level:rule.level,reason:rule.reason,quote:match[0],text:clause.trim()});
     }
    }
    // Carry only a proposed collection/action task across a comma, not the owner's future plans.
    if(/(?:计划|准备|打算|下次|明天|下周).{0,12}(?:问|了解|核实|争取|咨询|面见)|(?:尚未|还没).{0,8}(?:获取|确认|了解|核实)/.test(clause))inheritedPlan=true;
   }
  }
  evidence.sort((a,b)=>b.level-a.level||order.indexOf(a.code)-order.indexOf(b.code));
  const best=evidence[0];
  return {category:best?.code||'U',tags:[...new Set(evidence.map(e=>e.code))],basis:best?`${best.reason}：${best.quote}`:'',evidence};
 }
